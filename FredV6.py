right_front = Motor(Ports.PORT15, GearSetting.RATIO_18_1, False)
right_back  = Motor(Ports.PORT16, GearSetting.RATIO_18_1, False)
left_front = Motor(Ports.PORT20, GearSetting.RATIO_18_1, True)
left_back  = Motor(Ports.PORT19, GearSetting.RATIO_18_1, True)

RAMP_STEP = 4
DEADZONE = 5
TURN_SCALE = 0.5  # 1.0 = full turning, 0.5 = half turning

left_speed = 0
right_speed = 0

def deadzone(value):
    return 0 if abs(value) < DEADZONE else value

def ramp(current, target):
    if current < target:
        return min(current + RAMP_STEP, target)
    if current > target:
        return max(current - RAMP_STEP, target)
    return current

def set_motor_power(motor, power):
    motor.set_velocity(abs(power), PERCENT)
    motor.spin(FORWARD if power <= 0 else REVERSE)

Thread(screen_runtime)
Thread(clawtilter)

while True:
    throttle = deadzone(controller_1.axis3.position())
    turn = -deadzone(controller_1.axis1.position()) * TURN_SCALE

    left_target = throttle + turn
    right_target = throttle - turn

    # Scale both sides together if either exceeds 100%
    largest = max(abs(left_target), abs(right_target), 100)
    left_target = left_target * 100 / largest
    right_target = right_target * 100 / largest

    left_speed = ramp(left_speed, left_target)
    right_speed = ramp(right_speed, right_target)

    set_motor_power(left_front, left_speed)
    set_motor_power(left_back, left_speed)
    set_motor_power(right_front, right_speed)
    set_motor_power(right_back, right_speed)

    wait(20, MSEC)
